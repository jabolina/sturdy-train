#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"

CLUSTER_SIZE=5
JAVA_OPTS=""
IMAGE="infinispan/server:16.2"
COMPOSE_FILE="/tmp/ispn-resiliency-compose.yml"
PROMETHEUS_FILE="/tmp/ispn-resiliency-prometheus.yml"

usage() {
    cat <<EOF
Usage: $(basename "$0") [options]

Options:
  --size N              Number of Infinispan nodes (default: 5)
  --java-opts "OPTS"    JVM options passed to each server
  --image IMAGE         Server image (default: infinispan/server:16.2)

Examples:
  $(basename "$0")
  $(basename "$0") --size 3
  $(basename "$0") --size 3 --java-opts "-Xmx3g -XX:+UseZGC"
  $(basename "$0") --size 7 --image local/server:fix
EOF
    exit 1
}

while [ $# -gt 0 ]; do
    case "$1" in
        --size) CLUSTER_SIZE="$2"; shift 2 ;;
        --java-opts) JAVA_OPTS="$2"; shift 2 ;;
        --image) IMAGE="$2"; shift 2 ;;
        --help|-h) usage ;;
        *) echo "Error: unknown option '$1'"; usage ;;
    esac
done

if [ "$CLUSTER_SIZE" -lt 1 ] 2>/dev/null; then
    echo "Error: --size must be a positive integer"
    exit 1
fi

generate_compose() {
    cat <<EOF
# Generated by cluster.sh — do not edit.
# Cluster size: $CLUSTER_SIZE | Image: $IMAGE

services:
EOF

    local base_port=11222
    for i in $(seq 1 "$CLUSTER_SIZE"); do
        local host_port=$((base_port + (i - 1) * 100))
        local ip=$((10 + i))

        local env_block="      USER: admin
      PASS: password"
        if [ -n "$JAVA_OPTS" ]; then
            env_block="$env_block
      JAVA_OPTIONS: \"$JAVA_OPTS\""
        fi

        cat <<EOF
  ispn-${i}:
    image: $IMAGE
    container_name: ispn-${i}
    hostname: ispn-${i}
    ports:
      - "${host_port}:11222"
    environment:
${env_block}
    deploy:
      resources:
        limits:
          cpus: "2.0"
          memory: 1024M
    cap_add:
      - NET_ADMIN
      - SYS_PTRACE
    networks:
      cluster:
        ipv4_address: 172.18.10.${ip}
    volumes:
      - ${PROJECT_DIR}/infra/infinispan.xml:/opt/infinispan/server/conf/infinispan.xml
      - ${PROJECT_DIR}/infra/log4j2.xml:/opt/infinispan/server/conf/log4j2.xml
      - ${PROJECT_DIR}/logs/ispn-${i}:/opt/infinispan/server/log
    command: -c infinispan.xml --node-name=ispn-${i}

EOF
    done

    cat <<EOF
  prometheus:
    image: prom/prometheus:latest
    container_name: prometheus
    hostname: prometheus
    ports:
      - "9090:9090"
    volumes:
      - ${PROMETHEUS_FILE}:/etc/prometheus/prometheus.yml
    command:
      - '--config.file=/etc/prometheus/prometheus.yml'
      - '--storage.tsdb.path=/prometheus'
    networks:
      cluster:
        ipv4_address: 172.18.10.100

  grafana:
    image: grafana/grafana:latest
    container_name: grafana
    hostname: grafana
    ports:
      - "3000:3000"
    environment:
      GF_SECURITY_ADMIN_USER: admin
      GF_SECURITY_ADMIN_PASSWORD: admin
      GF_USERS_ALLOW_SIGN_UP: "false"
    volumes:
      - ${PROJECT_DIR}/grafana/provisioning:/etc/grafana/provisioning
    depends_on:
      - prometheus
    networks:
      cluster:
        ipv4_address: 172.18.10.101

networks:
  cluster:
    driver: bridge
    ipam:
      config:
        - subnet: 172.18.10.0/24
EOF
}

generate_prometheus() {
    cat <<EOF
global:
  scrape_interval: 5s

scrape_configs:
  - job_name: "infinispan"
    metrics_path: /metrics
    static_configs:
      - targets:
EOF
    for i in $(seq 1 "$CLUSTER_SIZE"); do
        cat <<EOF
          - "ispn-${i}:11222"
EOF
    done
}

echo "Generating cluster with $CLUSTER_SIZE nodes..."
if [ -n "$JAVA_OPTS" ]; then
    echo "  JAVA_OPTIONS: $JAVA_OPTS"
fi
echo "  Image: $IMAGE"

generate_compose > "$COMPOSE_FILE"
echo "  Compose: $COMPOSE_FILE"

generate_prometheus > "$PROMETHEUS_FILE"
echo "  Prometheus: $PROMETHEUS_FILE"

for i in $(seq 1 "$CLUSTER_SIZE"); do
    mkdir -p "$PROJECT_DIR/logs/ispn-${i}"
done

echo ""
echo "Starting cluster..."
echo "  Press CTRL-C to stop and tear down."
echo ""

cleanup() {
    echo ""
    echo "Tearing down cluster..."
    docker compose -f "$COMPOSE_FILE" down -v
    echo "Done."
}

trap cleanup EXIT

docker compose -f "$COMPOSE_FILE" up -d ispn-1
echo "Waiting for ispn-1 to start..."
until docker logs ispn-1 2>&1 | grep -q 'ISPN080001'; do
    sleep 1
done
echo "ispn-1 is ready — starting remaining nodes."

docker compose -f "$COMPOSE_FILE" up
